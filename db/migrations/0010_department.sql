-- S2-P004-025: additive Department level (Faculty -> Department -> Programme). No institutional rows are seeded.
CREATE TABLE public.department (
  department_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_code varchar(20) NOT NULL UNIQUE,
  department_name varchar(255) NOT NULL,
  faculty_id integer NOT NULL REFERENCES public.faculty(faculty_id) ON DELETE RESTRICT,
  is_active boolean NOT NULL DEFAULT true,
  CONSTRAINT department_code_nonblank CHECK (length(btrim(department_code)) > 0),
  CONSTRAINT department_name_nonblank CHECK (length(btrim(department_name)) > 0)
);
CREATE INDEX department_faculty_idx ON public.department(faculty_id);
ALTER TABLE public.programme ADD COLUMN department_id integer NULL REFERENCES public.department(department_id) ON DELETE RESTRICT;
CREATE INDEX programme_department_idx ON public.programme(department_id) WHERE department_id IS NOT NULL;

-- Audit now also covers department rows and programme department changes (still one row per programme change).
CREATE OR REPLACE FUNCTION public.db_academic_setup_audit() RETURNS trigger LANGUAGE plpgsql AS $fn$
DECLARE key_name text; before_row jsonb; after_row jsonb; entity_key integer; action_name text;
BEGIN
  IF TG_TABLE_NAME='programme' THEN
    IF TG_OP='INSERT' AND NEW.faculty_id IS NULL AND NEW.department_id IS NULL THEN RETURN NEW; END IF;
    IF TG_OP='UPDATE' THEN
      IF NEW.faculty_id IS NOT DISTINCT FROM OLD.faculty_id AND NEW.department_id IS NOT DISTINCT FROM OLD.department_id THEN RETURN NEW; END IF;
    END IF;
  END IF;
  PERFORM public.db_academic_setup_context();
  IF TG_OP='UPDATE' AND NEW IS NOT DISTINCT FROM OLD THEN RETURN NEW; END IF;
  IF TG_TABLE_NAME='academic_semester' THEN
    IF TG_OP='UPDATE' THEN
      IF NEW.is_current IS DISTINCT FROM OLD.is_current AND EXISTS (
        SELECT 1 FROM migration_meta.academic_switch_context c
        WHERE c.backend_pid=pg_backend_pid() AND c.transaction_id=txid_current()) THEN
        RETURN NEW;
      END IF;
    END IF;
  END IF;
  key_name := CASE TG_TABLE_NAME
    WHEN 'learning_centre' THEN 'learning_centre_id'
    WHEN 'faculty' THEN 'faculty_id'
    WHEN 'department' THEN 'department_id'
    WHEN 'programme' THEN 'programme_id'
    WHEN 'academic_semester' THEN 'semester_id'
    ELSE 'assignment_id' END;
  before_row := CASE WHEN TG_OP='INSERT' THEN NULL ELSE to_jsonb(OLD) END;
  after_row := to_jsonb(NEW);
  entity_key := (after_row->>key_name)::integer;
  action_name := CASE
    WHEN TG_TABLE_NAME='coordinator_assignment' AND TG_OP='UPDATE' THEN 'END_ASSIGNMENT'
    WHEN TG_TABLE_NAME='academic_semester' AND TG_OP='UPDATE' AND (before_row->>'is_current') IS DISTINCT FROM (after_row->>'is_current') THEN 'SET_CURRENT'
    ELSE TG_OP END;
  INSERT INTO public.academic_setup_audit_log(entity_type,entity_id,action,actor,reason,before_data,after_data)
  VALUES (TG_TABLE_NAME,entity_key,action_name,btrim(current_setting('app.access_actor',true)),
          btrim(current_setting('app.access_reason',true)),before_row,after_row);
  RETURN NEW;
END $fn$;
DROP TRIGGER academic_programme_audit ON public.programme;
CREATE TRIGGER academic_programme_audit AFTER INSERT OR UPDATE OF faculty_id, department_id ON public.programme
  FOR EACH ROW EXECUTE FUNCTION public.db_academic_setup_audit();

-- A department must belong to an active faculty when created or moved, and cannot move while programmes use it.
CREATE FUNCTION public.db_academic_department_guard() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF TG_OP='UPDATE' THEN
    IF NEW.faculty_id IS NOT DISTINCT FROM OLD.faculty_id THEN RETURN NEW; END IF;
  END IF;
  PERFORM public.db_academic_setup_context();
  IF TG_OP='UPDATE' THEN
    -- Take the row lock first so concurrent programme assignments (FOR SHARE) finish before the check below.
    PERFORM 1 FROM public.department WHERE department_id=OLD.department_id FOR UPDATE;
    IF EXISTS (SELECT 1 FROM public.programme WHERE department_id=OLD.department_id) THEN
      RAISE EXCEPTION 'ACADEMIC_SETUP:DEPARTMENT_HAS_PROGRAMMES' USING ERRCODE='23514';
    END IF;
  END IF;
  PERFORM 1 FROM public.faculty WHERE faculty_id=NEW.faculty_id AND is_active FOR SHARE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'ACADEMIC_SETUP:REFERENCE_INACTIVE' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END $fn$;

-- A programme with a department always carries that department's faculty.
CREATE FUNCTION public.db_academic_programme_department_guard() RETURNS trigger LANGUAGE plpgsql AS $fn$
DECLARE dept_faculty integer; dept_active boolean;
BEGIN
  IF NEW.department_id IS NULL THEN RETURN NEW; END IF;
  IF TG_OP='UPDATE' THEN
    IF NEW.department_id IS NOT DISTINCT FROM OLD.department_id AND NEW.faculty_id IS NOT DISTINCT FROM OLD.faculty_id THEN RETURN NEW; END IF;
  END IF;
  PERFORM public.db_academic_setup_context();
  SELECT faculty_id,is_active INTO dept_faculty,dept_active FROM public.department WHERE department_id=NEW.department_id FOR SHARE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'ACADEMIC_SETUP:NOT_FOUND' USING ERRCODE='23514';
  END IF;
  IF TG_OP='INSERT' OR NEW.department_id IS DISTINCT FROM OLD.department_id THEN
    IF NOT dept_active THEN
      RAISE EXCEPTION 'ACADEMIC_SETUP:REFERENCE_INACTIVE' USING ERRCODE='23514';
    END IF;
  END IF;
  IF NEW.faculty_id IS DISTINCT FROM dept_faculty THEN
    RAISE EXCEPTION 'ACADEMIC_SETUP:PROGRAMME_FACULTY_MISMATCH' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END $fn$;

CREATE TRIGGER academic_department_context BEFORE INSERT OR UPDATE ON public.department
  FOR EACH ROW EXECUTE FUNCTION public.db_academic_setup_context_trigger();
CREATE TRIGGER academic_department_reference_guard BEFORE INSERT OR UPDATE OF faculty_id ON public.department
  FOR EACH ROW EXECUTE FUNCTION public.db_academic_department_guard();
CREATE TRIGGER academic_department_audit AFTER INSERT OR UPDATE ON public.department
  FOR EACH ROW EXECUTE FUNCTION public.db_academic_setup_audit();
CREATE TRIGGER no_academic_department_delete BEFORE DELETE OR TRUNCATE ON public.department
  FOR EACH STATEMENT EXECUTE FUNCTION public.db_immutable();
CREATE TRIGGER academic_programme_department_guard BEFORE INSERT OR UPDATE OF department_id, faculty_id ON public.programme
  FOR EACH ROW EXECUTE FUNCTION public.db_academic_programme_department_guard();

REVOKE ALL ON public.department FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.db_academic_department_guard() FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.db_academic_programme_department_guard() FROM PUBLIC;
