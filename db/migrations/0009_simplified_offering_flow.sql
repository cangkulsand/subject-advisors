UPDATE public.student_profile SET learning_centre_id = (SELECT learning_centre_id FROM public.learning_centre WHERE centre_code = 'KL') WHERE learning_centre_id IS NULL;

-- No row means Pending.
CREATE TABLE public.offering_decision (
  decision_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  programme_id integer NOT NULL REFERENCES public.programme(programme_id) ON DELETE RESTRICT,
  learning_centre_id integer NOT NULL REFERENCES public.learning_centre(learning_centre_id) ON DELETE RESTRICT,
  semester_id integer NOT NULL REFERENCES public.academic_semester(semester_id) ON DELETE RESTRICT,
  subject_id integer NOT NULL REFERENCES public.subject(subject_id) ON DELETE RESTRICT,
  status varchar(10) NOT NULL,
  decided_by varchar(255) NOT NULL,
  decided_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT offering_decision_status_rule CHECK (status IN ('APPROVED','REMOVED')),
  CONSTRAINT offering_decision_decided_by_rule CHECK (length(btrim(decided_by)) > 0),
  CONSTRAINT offering_decision_scope_subject_unique UNIQUE (programme_id, learning_centre_id, semester_id, subject_id)
);

CREATE TABLE public.offering_decision_audit (
  audit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  programme_id integer NOT NULL REFERENCES public.programme(programme_id) ON DELETE RESTRICT,
  learning_centre_id integer NOT NULL REFERENCES public.learning_centre(learning_centre_id) ON DELETE RESTRICT,
  semester_id integer NOT NULL REFERENCES public.academic_semester(semester_id) ON DELETE RESTRICT,
  subject_id integer NOT NULL REFERENCES public.subject(subject_id) ON DELETE RESTRICT,
  before_status varchar(10) NOT NULL,
  after_status varchar(10) NOT NULL,
  import_batch_id integer NULL REFERENCES public.academic_import_batch(import_batch_id) ON DELETE RESTRICT,
  affected_picks integer NOT NULL DEFAULT 0,
  recorded_by varchar(255) NOT NULL,
  recorded_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT offering_decision_audit_before_rule CHECK (before_status IN ('PENDING','APPROVED','REMOVED')),
  CONSTRAINT offering_decision_audit_after_rule CHECK (after_status IN ('PENDING','APPROVED','REMOVED')),
  CONSTRAINT offering_decision_audit_change_rule CHECK (before_status <> after_status),
  CONSTRAINT offering_decision_audit_picks_rule CHECK (affected_picks >= 0),
  CONSTRAINT offering_decision_audit_recorded_by_rule CHECK (length(btrim(recorded_by)) > 0)
);
CREATE INDEX offering_decision_audit_scope_idx ON public.offering_decision_audit(programme_id, learning_centre_id, semester_id, audit_id);
CREATE TRIGGER immutable_offering_decision_audit BEFORE UPDATE OR DELETE ON public.offering_decision_audit FOR EACH ROW EXECUTE FUNCTION public.db_immutable();
CREATE TRIGGER immutable_offering_decision_audit_truncate BEFORE TRUNCATE ON public.offering_decision_audit EXECUTE FUNCTION public.db_immutable();

CREATE TABLE public.offering_pick_withdrawal (
  withdrawal_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  audit_id bigint NOT NULL REFERENCES public.offering_decision_audit(audit_id) ON DELETE RESTRICT,
  student_id integer NOT NULL REFERENCES public.student_profile(student_id) ON DELETE RESTRICT,
  semester_id integer NOT NULL REFERENCES public.academic_semester(semester_id) ON DELETE RESTRICT,
  subject_id integer NOT NULL REFERENCES public.subject(subject_id) ON DELETE RESTRICT,
  withdrawn_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX offering_pick_withdrawal_student_idx ON public.offering_pick_withdrawal(student_id, semester_id);
CREATE TRIGGER immutable_offering_pick_withdrawal BEFORE UPDATE OR DELETE ON public.offering_pick_withdrawal FOR EACH ROW EXECUTE FUNCTION public.db_immutable();
CREATE TRIGGER immutable_offering_pick_withdrawal_truncate BEFORE TRUNCATE ON public.offering_pick_withdrawal EXECUTE FUNCTION public.db_immutable();

REVOKE ALL ON public.offering_decision, public.offering_decision_audit, public.offering_pick_withdrawal FROM PUBLIC;
