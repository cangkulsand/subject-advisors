-- S2-P004-008: additive academic administration. No institutional rows are seeded.
ALTER TABLE public.learning_centre ADD COLUMN is_active boolean NOT NULL DEFAULT true;
CREATE TABLE public.faculty (
  faculty_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  faculty_code varchar(20) NOT NULL UNIQUE,
  faculty_name varchar(255) NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  CONSTRAINT faculty_code_nonblank CHECK (length(btrim(faculty_code)) > 0),
  CONSTRAINT faculty_name_nonblank CHECK (length(btrim(faculty_name)) > 0)
);
ALTER TABLE public.programme ADD COLUMN faculty_id integer NULL REFERENCES public.faculty(faculty_id) ON DELETE RESTRICT;
ALTER TABLE public.academic_semester ADD COLUMN is_current boolean NOT NULL DEFAULT false;
CREATE UNIQUE INDEX academic_semester_one_current_idx ON public.academic_semester (is_current) WHERE is_current;

CREATE TABLE public.coordinator_assignment (
  assignment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  access_assignment_id integer NOT NULL REFERENCES public.user_access_assignment(access_assignment_id) ON DELETE RESTRICT,
  faculty_id integer NOT NULL REFERENCES public.faculty(faculty_id) ON DELETE RESTRICT,
  programme_id integer NOT NULL REFERENCES public.programme(programme_id) ON DELETE RESTRICT,
  learning_centre_id integer NOT NULL REFERENCES public.learning_centre(learning_centre_id) ON DELETE RESTRICT,
  started_at timestamptz NOT NULL DEFAULT now(),
  ended_at timestamptz,
  CONSTRAINT coordinator_assignment_time_rule CHECK (ended_at IS NULL OR ended_at >= started_at)
);
CREATE UNIQUE INDEX coordinator_assignment_one_live_scope_idx
  ON public.coordinator_assignment(access_assignment_id, programme_id, learning_centre_id) WHERE ended_at IS NULL;
CREATE INDEX coordinator_assignment_scope_idx ON public.coordinator_assignment(programme_id,learning_centre_id,faculty_id) WHERE ended_at IS NULL;

CREATE TABLE public.academic_setup_audit_log (
  audit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type varchar(40) NOT NULL,
  entity_id integer NOT NULL,
  action varchar(40) NOT NULL,
  actor varchar(255) NOT NULL,
  reason text NOT NULL,
  before_data jsonb,
  after_data jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT academic_setup_audit_actor_rule CHECK (length(btrim(actor)) > 0),
  CONSTRAINT academic_setup_audit_reason_rule CHECK (reason=btrim(reason) AND length(reason) BETWEEN 1 AND 500)
);
CREATE TABLE migration_meta.academic_switch_context (
  backend_pid integer NOT NULL,
  transaction_id bigint NOT NULL,
  target_semester_id integer NOT NULL,
  PRIMARY KEY (backend_pid,transaction_id)
);
REVOKE ALL ON migration_meta.academic_switch_context FROM PUBLIC;

CREATE FUNCTION public.db_academic_setup_context() RETURNS void LANGUAGE plpgsql AS $fn$
BEGIN
  IF nullif(btrim(current_setting('app.access_actor',true)),'') IS NULL OR
     nullif(btrim(current_setting('app.access_reason',true)),'') IS NULL OR
     length(btrim(current_setting('app.access_reason',true))) > 500 THEN
    RAISE EXCEPTION 'ACADEMIC_SETUP:INVALID_REQUEST' USING ERRCODE='23514';
  END IF;
END $fn$;

CREATE FUNCTION public.db_academic_setup_context_trigger() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  PERFORM public.db_academic_setup_context();
  IF TG_TABLE_NAME='academic_semester' THEN
    IF TG_OP='INSERT' THEN
      IF NEW.is_current THEN
        RAISE EXCEPTION 'ACADEMIC_SETUP:INVALID_REQUEST' USING ERRCODE='23514';
      END IF;
    ELSIF NEW.is_current IS DISTINCT FROM OLD.is_current THEN
      IF NOT EXISTS (SELECT 1 FROM migration_meta.academic_switch_context c
        WHERE c.backend_pid=pg_backend_pid() AND c.transaction_id=txid_current()) THEN
        RAISE EXCEPTION 'ACADEMIC_SETUP:INVALID_REQUEST' USING ERRCODE='23514';
      END IF;
    END IF;
  END IF;
  RETURN NEW;
END $fn$;

CREATE FUNCTION public.db_academic_setup_audit() RETURNS trigger LANGUAGE plpgsql AS $fn$
DECLARE key_name text; before_row jsonb; after_row jsonb; entity_key integer; action_name text;
BEGIN
  IF TG_TABLE_NAME='programme' THEN
    IF TG_OP='INSERT' AND NEW.faculty_id IS NULL THEN RETURN NEW; END IF;
    IF TG_OP='UPDATE' THEN
      IF NEW.faculty_id IS NOT DISTINCT FROM OLD.faculty_id THEN RETURN NEW; END IF;
    END IF;
  END IF;
  PERFORM public.db_academic_setup_context();
  IF TG_OP='UPDATE' AND NEW IS NOT DISTINCT FROM OLD THEN RETURN NEW; END IF;
  IF TG_TABLE_NAME='academic_semester' THEN
    IF TG_OP='UPDATE' THEN
      IF NEW.is_current IS DISTINCT FROM OLD.is_current AND EXISTS (
        SELECT 1 FROM migration_meta.academic_switch_context c
        WHERE c.backend_pid=pg_backend_pid() AND c.transaction_id=txid_current()) THEN
        RETURN NEW;
      END IF;
    END IF;
  END IF;
  IF TG_TABLE_NAME='programme' THEN
    IF TG_OP='INSERT' AND NEW.faculty_id IS NULL THEN RETURN NEW; END IF;
    IF TG_OP='UPDATE' THEN
      IF NEW.faculty_id IS NOT DISTINCT FROM OLD.faculty_id THEN RETURN NEW; END IF;
    END IF;
  END IF;
  key_name := CASE TG_TABLE_NAME
    WHEN 'learning_centre' THEN 'learning_centre_id'
    WHEN 'faculty' THEN 'faculty_id'
    WHEN 'programme' THEN 'programme_id'
    WHEN 'academic_semester' THEN 'semester_id'
    ELSE 'assignment_id' END;
  before_row := CASE WHEN TG_OP='INSERT' THEN NULL ELSE to_jsonb(OLD) END;
  after_row := to_jsonb(NEW);
  entity_key := (after_row->>key_name)::integer;
  action_name := CASE
    WHEN TG_TABLE_NAME='coordinator_assignment' AND TG_OP='UPDATE' THEN 'END_ASSIGNMENT'
    WHEN TG_TABLE_NAME='academic_semester' AND TG_OP='UPDATE' AND (before_row->>'is_current') IS DISTINCT FROM (after_row->>'is_current') THEN 'SET_CURRENT'
    ELSE TG_OP END;
  INSERT INTO public.academic_setup_audit_log(entity_type,entity_id,action,actor,reason,before_data,after_data)
  VALUES (TG_TABLE_NAME,entity_key,action_name,btrim(current_setting('app.access_actor',true)),
          btrim(current_setting('app.access_reason',true)),before_row,after_row);
  RETURN NEW;
END $fn$;

CREATE FUNCTION public.db_academic_setup_reference_guard() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF TG_OP='INSERT' THEN
    IF NEW.faculty_id IS NULL THEN RETURN NEW; END IF;
  ELSIF NEW.faculty_id IS NOT DISTINCT FROM OLD.faculty_id THEN
    RETURN NEW;
  END IF;
  PERFORM public.db_academic_setup_context();
  IF TG_OP='UPDATE' THEN
    IF EXISTS (SELECT 1 FROM public.coordinator_assignment WHERE programme_id=NEW.programme_id AND ended_at IS NULL) THEN
      RAISE EXCEPTION 'ACADEMIC_SETUP:ASSIGNMENT_ACTIVE' USING ERRCODE='23514';
    END IF;
  END IF;
  IF NEW.faculty_id IS NOT NULL THEN
    PERFORM 1 FROM public.faculty WHERE faculty_id=NEW.faculty_id AND is_active FOR SHARE;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'ACADEMIC_SETUP:REFERENCE_INACTIVE' USING ERRCODE='23514';
    END IF;
  END IF;
  RETURN NEW;
END $fn$;

CREATE FUNCTION public.db_academic_setup_assignment_guard() RETURNS trigger LANGUAGE plpgsql AS $fn$
DECLARE programme_faculty integer; programme_status varchar(20);
BEGIN
  PERFORM public.db_academic_setup_context();
  IF TG_OP='UPDATE' THEN
    IF (to_jsonb(NEW)-'ended_at') IS DISTINCT FROM (to_jsonb(OLD)-'ended_at') OR
       OLD.ended_at IS NOT NULL OR NEW.ended_at IS NULL THEN
      RAISE EXCEPTION 'ACADEMIC_SETUP:ASSIGNMENT_ENDED' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
  END IF;
  IF NEW.ended_at IS NOT NULL THEN
    RAISE EXCEPTION 'ACADEMIC_SETUP:INVALID_REQUEST' USING ERRCODE='23514';
  END IF;
  -- SHARE blocks non-key status/reference updates and membership deletion until commit.
  PERFORM 1 FROM public.user_access_assignment a
    WHERE a.access_assignment_id=NEW.access_assignment_id AND a.access_status='ACTIVE' FOR SHARE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'ACADEMIC_SETUP:ACCOUNT_INACTIVE' USING ERRCODE='23514';
  END IF;
  PERFORM 1 FROM public.user_role_assignment r
    WHERE r.access_assignment_id=NEW.access_assignment_id AND r.app_role='COORDINATOR' FOR SHARE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'ACADEMIC_SETUP:COORDINATOR_ROLE_REQUIRED' USING ERRCODE='23514';
  END IF;
  SELECT faculty_id,status INTO programme_faculty,programme_status
    FROM public.programme WHERE programme_id=NEW.programme_id FOR SHARE;
  IF NOT FOUND OR coalesce(upper(programme_status),'ACTIVE')<>'ACTIVE' THEN
    RAISE EXCEPTION 'ACADEMIC_SETUP:REFERENCE_INACTIVE' USING ERRCODE='23514';
  END IF;
  PERFORM 1 FROM public.faculty WHERE faculty_id=NEW.faculty_id AND is_active FOR SHARE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'ACADEMIC_SETUP:REFERENCE_INACTIVE' USING ERRCODE='23514';
  END IF;
  PERFORM 1 FROM public.learning_centre WHERE learning_centre_id=NEW.learning_centre_id AND is_active FOR SHARE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'ACADEMIC_SETUP:REFERENCE_INACTIVE' USING ERRCODE='23514';
  END IF;
  IF programme_faculty IS DISTINCT FROM NEW.faculty_id THEN
    RAISE EXCEPTION 'ACADEMIC_SETUP:PROGRAMME_FACULTY_MISMATCH' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END $fn$;

