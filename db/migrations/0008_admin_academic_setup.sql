CREATE FUNCTION public.db_set_current_semester(target_semester_id integer) RETURNS void LANGUAGE plpgsql AS $fn$
DECLARE prior_id integer;
BEGIN
  PERFORM public.db_academic_setup_context();
  PERFORM pg_advisory_xact_lock(260000,8);
  IF NOT EXISTS (SELECT 1 FROM public.academic_semester WHERE semester_id=target_semester_id) THEN
    RAISE EXCEPTION 'ACADEMIC_SETUP:NOT_FOUND' USING ERRCODE='23514';
  END IF;
  SELECT semester_id INTO prior_id FROM public.academic_semester WHERE is_current FOR UPDATE;
  IF prior_id IS NOT DISTINCT FROM target_semester_id THEN RETURN; END IF;
  INSERT INTO migration_meta.academic_switch_context(backend_pid,transaction_id,target_semester_id)
    VALUES (pg_backend_pid(),txid_current(),target_semester_id);
  IF prior_id IS NOT NULL THEN
    UPDATE public.academic_semester SET is_current=false WHERE semester_id=prior_id;
  END IF;
  UPDATE public.academic_semester SET is_current=true WHERE semester_id=target_semester_id;
  INSERT INTO public.academic_setup_audit_log(entity_type,entity_id,action,actor,reason,before_data,after_data)
    VALUES ('academic_semester',target_semester_id,'SET_CURRENT',
      btrim(current_setting('app.access_actor',true)),btrim(current_setting('app.access_reason',true)),
      CASE WHEN prior_id IS NULL THEN NULL ELSE jsonb_build_object('semesterId',prior_id) END,
      jsonb_build_object('semesterId',target_semester_id));
  DELETE FROM migration_meta.academic_switch_context
    WHERE backend_pid=pg_backend_pid() AND transaction_id=txid_current();
END $fn$;

