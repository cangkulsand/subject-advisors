-- Preserve the capacity rule used to interpret stored section decisions.
CREATE FUNCTION public.db_preserve_capacity_rule() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
 IF EXISTS(SELECT 1 FROM public.proposed_class_section WHERE capacity_rule_id=OLD.capacity_rule_id) THEN
  RAISE EXCEPTION 'Referenced capacity rules are immutable; create a new rule' USING ERRCODE='23514';
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF; RETURN NEW;
END $fn$;
CREATE TRIGGER preserve_capacity_rule BEFORE UPDATE OR DELETE ON public.class_capacity_rule FOR EACH ROW EXECUTE FUNCTION public.db_preserve_capacity_rule();

CREATE FUNCTION public.db_section_capacity() RETURNS trigger LANGUAGE plpgsql AS $fn$
DECLARE policy public.class_capacity_rule%ROWTYPE; subject_type varchar; included boolean;
BEGIN
 SELECT * INTO policy FROM public.class_capacity_rule WHERE capacity_rule_id=NEW.capacity_rule_id FOR SHARE;
 SELECT s.class_type,s.include_in_offering_forecast INTO subject_type,included
 FROM public.forecast_subject_demand d JOIN public.subject s USING(subject_id) WHERE d.demand_id=NEW.demand_id FOR SHARE OF d,s;
 IF policy.capacity_rule_id IS NULL THEN RAISE EXCEPTION 'Missing capacity rule' USING ERRCODE='23503'; END IF;
 IF included IS DISTINCT FROM true OR subject_type IS DISTINCT FROM policy.class_type THEN
  RAISE EXCEPTION 'Subject forecast classification does not match capacity rule' USING ERRCODE='23514';
 END IF;
 IF NEW.expected_students>coalesce(policy.exception_maximum,policy.normal_maximum) THEN
  RAISE EXCEPTION 'Expected enrollment exceeds configured capacity' USING ERRCODE='23514';
 END IF;
 IF NEW.expected_students>policy.normal_maximum AND nullif(btrim(NEW.justification),'') IS NULL THEN
  RAISE EXCEPTION 'Capacity exception requires justification' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $fn$;
CREATE TRIGGER section_capacity BEFORE INSERT OR UPDATE ON public.proposed_class_section FOR EACH ROW EXECUTE FUNCTION public.db_section_capacity();
