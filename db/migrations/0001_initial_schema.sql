-- Prevent parent remapping from invalidating historical child memberships.
CREATE FUNCTION public.db_preserve_membership() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF TG_TABLE_NAME='student_profile' THEN
    IF NEW.curriculum_id IS DISTINCT FROM OLD.curriculum_id AND (
      EXISTS (SELECT 1 FROM public.academic_record WHERE student_id=OLD.student_id) OR
      EXISTS (SELECT 1 FROM public.semester_offering WHERE student_id=OLD.student_id) OR
      EXISTS (SELECT 1 FROM public.academic_plan WHERE student_id=OLD.student_id) OR
      EXISTS (SELECT 1 FROM public.simulation_scenario WHERE student_id=OLD.student_id)) THEN
      RAISE EXCEPTION 'Controlled curriculum reconciliation required' USING ERRCODE='23514';
    END IF;
  ELSIF TG_TABLE_NAME='academic_plan' THEN
    IF NEW.student_id IS DISTINCT FROM OLD.student_id THEN
      RAISE EXCEPTION 'Plan ownership is immutable' USING ERRCODE='23514';
    END IF;
  ELSIF TG_TABLE_NAME='simulation_scenario' THEN
    IF NEW.student_id IS DISTINCT FROM OLD.student_id THEN
      RAISE EXCEPTION 'Scenario ownership is immutable' USING ERRCODE='23514';
    END IF;
  ELSIF TG_TABLE_NAME='curriculum_subject' THEN
    IF NEW.curriculum_id IS DISTINCT FROM OLD.curriculum_id OR NEW.subject_id IS DISTINCT FROM OLD.subject_id THEN
      RAISE EXCEPTION 'Curriculum mapping identity is immutable; create a new mapping' USING ERRCODE='23514';
    END IF;
  ELSIF TG_TABLE_NAME='subject' THEN
    IF NEW.credit_hours IS DISTINCT FROM OLD.credit_hours AND (
      EXISTS(SELECT 1 FROM public.academic_record WHERE subject_id=OLD.subject_id) OR
      EXISTS(SELECT 1 FROM public.imported_subject_record WHERE subject_id=OLD.subject_id)) THEN
      RAISE EXCEPTION 'Recorded subject credits require controlled reconciliation' USING ERRCODE='23514';
    END IF;
  END IF;
  RETURN NEW;
END $fn$;
CREATE TRIGGER preserve_student_curriculum BEFORE UPDATE ON public.student_profile FOR EACH ROW EXECUTE FUNCTION public.db_preserve_membership();
CREATE TRIGGER preserve_plan_owner BEFORE UPDATE ON public.academic_plan FOR EACH ROW EXECUTE FUNCTION public.db_preserve_membership();
CREATE TRIGGER preserve_scenario_owner BEFORE UPDATE ON public.simulation_scenario FOR EACH ROW EXECUTE FUNCTION public.db_preserve_membership();
CREATE TRIGGER preserve_mapping_identity BEFORE UPDATE ON public.curriculum_subject FOR EACH ROW EXECUTE FUNCTION public.db_preserve_membership();
CREATE TRIGGER preserve_recorded_credits BEFORE UPDATE ON public.subject FOR EACH ROW EXECUTE FUNCTION public.db_preserve_membership();

CREATE FUNCTION public.db_prerequisite_integrity() RETURNS trigger LANGUAGE plpgsql AS $fn$
DECLARE curriculum integer; other_curriculum integer;
BEGIN
  SELECT curriculum_id INTO curriculum FROM public.curriculum_subject WHERE curriculum_subject_id=NEW.curriculum_subject_id FOR SHARE;
  SELECT curriculum_id INTO other_curriculum FROM public.curriculum_subject WHERE curriculum_subject_id=NEW.required_curriculum_subject_id FOR SHARE;
  IF curriculum IS NULL OR curriculum IS DISTINCT FROM other_curriculum THEN
    RAISE EXCEPTION 'Prerequisite curriculum mismatch' USING ERRCODE='23514';
  END IF;
  PERFORM pg_advisory_xact_lock(260001,curriculum);
  IF NEW.requirement_type='MANDATORY' AND EXISTS (
    WITH RECURSIVE dependencies(id) AS (
      SELECT NEW.required_curriculum_subject_id
      UNION
      SELECT p.required_curriculum_subject_id FROM public.subject_prerequisite p JOIN dependencies d ON p.curriculum_subject_id=d.id
      WHERE p.requirement_type='MANDATORY' AND p.prerequisite_id IS DISTINCT FROM NEW.prerequisite_id
    ) SELECT 1 FROM dependencies WHERE id=NEW.curriculum_subject_id
  ) THEN RAISE EXCEPTION 'Mandatory prerequisite cycle' USING ERRCODE='23514'; END IF;
  RETURN NEW;
END $fn$;
CREATE TRIGGER prerequisite_integrity BEFORE INSERT OR UPDATE ON public.subject_prerequisite FOR EACH ROW EXECUTE FUNCTION public.db_prerequisite_integrity();

-- Parent-row locks serialize snapshot mutation with creation of forecast references.
CREATE FUNCTION public.db_lock_unused_batch(batch integer) RETURNS void LANGUAGE plpgsql AS $fn$
BEGIN
  PERFORM 1 FROM public.academic_import_batch WHERE import_batch_id=batch FOR UPDATE;
  IF EXISTS(SELECT 1 FROM public.forecast_run WHERE import_batch_id=batch) THEN
    RAISE EXCEPTION 'Referenced import snapshots are immutable' USING ERRCODE='23514';
  END IF;
END $fn$;
CREATE FUNCTION public.db_import_integrity() RETURNS trigger LANGUAGE plpgsql AS $fn$
DECLARE batch integer; old_batch integer; curriculum integer;
BEGIN
  IF TG_TABLE_NAME='academic_import_batch' THEN
    PERFORM public.db_lock_unused_batch(OLD.import_batch_id);
  ELSIF TG_TABLE_NAME='imported_student' THEN
    IF TG_OP<>'INSERT' THEN PERFORM public.db_lock_unused_batch(OLD.import_batch_id); END IF;
    IF TG_OP<>'DELETE' THEN PERFORM public.db_lock_unused_batch(NEW.import_batch_id); END IF;
    IF TG_OP='UPDATE' AND NEW.curriculum_id IS DISTINCT FROM OLD.curriculum_id AND
       EXISTS(SELECT 1 FROM public.imported_subject_record WHERE imported_student_id=OLD.imported_student_id) THEN
      RAISE EXCEPTION 'Imported curriculum reconciliation required' USING ERRCODE='23514';
    END IF;
  ELSE
    IF TG_OP<>'DELETE' THEN
      SELECT s.import_batch_id,s.curriculum_id INTO batch,curriculum FROM public.imported_student s WHERE imported_student_id=NEW.imported_student_id FOR SHARE;
      PERFORM public.db_lock_unused_batch(batch);
      IF NOT EXISTS(SELECT 1 FROM public.curriculum_subject WHERE curriculum_id=curriculum AND subject_id=NEW.subject_id) THEN
        RAISE EXCEPTION 'Imported subject curriculum mismatch' USING ERRCODE='23514';
      END IF;
    END IF;
    IF TG_OP<>'INSERT' THEN
      SELECT import_batch_id INTO old_batch FROM public.imported_student WHERE imported_student_id=OLD.imported_student_id FOR SHARE;
      PERFORM public.db_lock_unused_batch(old_batch);
    END IF;
  END IF;
  IF TG_OP='DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $fn$;
CREATE TRIGGER preserve_batch BEFORE UPDATE OR DELETE ON public.academic_import_batch FOR EACH ROW EXECUTE FUNCTION public.db_import_integrity();
CREATE TRIGGER imported_student_integrity BEFORE INSERT OR UPDATE OR DELETE ON public.imported_student FOR EACH ROW EXECUTE FUNCTION public.db_import_integrity();
CREATE TRIGGER imported_record_integrity BEFORE INSERT OR UPDATE OR DELETE ON public.imported_subject_record FOR EACH ROW EXECUTE FUNCTION public.db_import_integrity();
CREATE TRIGGER no_batch_truncate BEFORE TRUNCATE ON public.academic_import_batch EXECUTE FUNCTION public.db_immutable();
CREATE TRIGGER no_imported_student_truncate BEFORE TRUNCATE ON public.imported_student EXECUTE FUNCTION public.db_immutable();
CREATE TRIGGER no_imported_record_truncate BEFORE TRUNCATE ON public.imported_subject_record EXECUTE FUNCTION public.db_immutable();

CREATE FUNCTION public.db_forecast_run_integrity() RETURNS trigger LANGUAGE plpgsql AS $fn$
DECLARE centre integer; parent public.forecast_run%ROWTYPE;
BEGIN
  IF TG_OP<>'INSERT' AND (OLD.finalized_at IS NOT NULL OR OLD.status IN ('FINALIZED','SUPERSEDED','ARCHIVED')) THEN
    IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Finalized forecast cannot be deleted' USING ERRCODE='23514'; END IF;
    IF (to_jsonb(NEW)-'status') IS DISTINCT FROM (to_jsonb(OLD)-'status') OR
      NOT (NEW.status=OLD.status OR (OLD.status='FINALIZED' AND NEW.status IN ('SUPERSEDED','ARCHIVED')) OR (OLD.status='SUPERSEDED' AND NEW.status='ARCHIVED')) THEN
      RAISE EXCEPTION 'Finalized forecast payload/lifecycle is read-only' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
  END IF;
  IF TG_OP='DELETE' THEN RETURN OLD; END IF;
  SELECT learning_centre_id INTO centre FROM public.academic_import_batch WHERE import_batch_id=NEW.import_batch_id FOR UPDATE;
  IF centre IS NULL OR centre IS DISTINCT FROM NEW.learning_centre_id THEN
    RAISE EXCEPTION 'Forecast source batch centre mismatch' USING ERRCODE='23514';
  END IF;
  IF TG_OP='UPDATE' AND (
     NEW.import_batch_id IS DISTINCT FROM OLD.import_batch_id OR
     NEW.target_semester_id IS DISTINCT FROM OLD.target_semester_id OR
     NEW.learning_centre_id IS DISTINCT FROM OLD.learning_centre_id OR
     NEW.version_number IS DISTINCT FROM OLD.version_number OR
     NEW.parent_forecast_run_id IS DISTINCT FROM OLD.parent_forecast_run_id OR
     NEW.scenario_assumptions IS DISTINCT FROM OLD.scenario_assumptions OR
     NEW.generated_by IS DISTINCT FROM OLD.generated_by OR
     NEW.generated_at IS DISTINCT FROM OLD.generated_at) THEN
    RAISE EXCEPTION 'Forecast identity/source/assumptions require a new version' USING ERRCODE='23514';
  END IF;
  IF NEW.parent_forecast_run_id IS NOT NULL THEN
    SELECT * INTO parent FROM public.forecast_run WHERE forecast_run_id=NEW.parent_forecast_run_id FOR SHARE;
    IF parent.forecast_run_id IS NULL OR parent.learning_centre_id<>NEW.learning_centre_id OR
       parent.target_semester_id<>NEW.target_semester_id OR parent.version_number>=NEW.version_number THEN
      RAISE EXCEPTION 'Forecast parent scope/version mismatch' USING ERRCODE='23514';
    END IF;
  END IF;
  IF TG_OP='INSERT' AND NEW.status NOT IN ('DRAFT','UNDER_REVIEW') THEN
    RAISE EXCEPTION 'Create a draft forecast before finalization' USING ERRCODE='23514';
  END IF;
  IF NEW.status IN ('SUPERSEDED','ARCHIVED') THEN
    RAISE EXCEPTION 'Finalize a forecast before lifecycle archival' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END $fn$;
CREATE TRIGGER forecast_run_integrity BEFORE INSERT OR UPDATE OR DELETE ON public.forecast_run FOR EACH ROW EXECUTE FUNCTION public.db_forecast_run_integrity();

CREATE FUNCTION public.db_lock_editable_forecast(run integer) RETURNS void LANGUAGE plpgsql AS $fn$
DECLARE state varchar; finalized timestamptz;
BEGIN
  SELECT status,finalized_at INTO state,finalized FROM public.forecast_run WHERE forecast_run_id=run FOR UPDATE;
  IF state IS NULL THEN RAISE EXCEPTION 'Forecast missing' USING ERRCODE='23503'; END IF;
  IF finalized IS NOT NULL OR state NOT IN ('DRAFT','UNDER_REVIEW') THEN
    RAISE EXCEPTION 'Finalized forecast results and decisions are read-only' USING ERRCODE='23514';
  END IF;
END $fn$;
CREATE FUNCTION public.db_forecast_payload_integrity() RETURNS trigger LANGUAGE plpgsql AS $fn$
DECLARE new_run integer; old_run integer;
BEGIN
  IF TG_TABLE_NAME='forecast_subject_demand' THEN
    IF TG_OP<>'DELETE' THEN new_run:=NEW.forecast_run_id; END IF;
    IF TG_OP<>'INSERT' THEN old_run:=OLD.forecast_run_id; END IF;
  ELSIF TG_TABLE_NAME='proposed_class_section' THEN
    IF TG_OP<>'DELETE' THEN SELECT forecast_run_id INTO new_run FROM public.forecast_subject_demand WHERE demand_id=NEW.demand_id FOR SHARE; END IF;
    IF TG_OP<>'INSERT' THEN SELECT forecast_run_id INTO old_run FROM public.forecast_subject_demand WHERE demand_id=OLD.demand_id FOR SHARE; END IF;
  ELSE
    SELECT d.forecast_run_id INTO new_run FROM public.proposed_class_section s JOIN public.forecast_subject_demand d USING(demand_id) WHERE s.proposed_section_id=NEW.proposed_section_id FOR SHARE OF s,d;
  END IF;
  IF old_run IS NOT NULL THEN PERFORM public.db_lock_editable_forecast(old_run); END IF;
  IF new_run IS NOT NULL AND new_run IS DISTINCT FROM old_run THEN PERFORM public.db_lock_editable_forecast(new_run); END IF;
  IF TG_OP='DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $fn$;
CREATE TRIGGER demand_editable BEFORE INSERT OR UPDATE OR DELETE ON public.forecast_subject_demand FOR EACH ROW EXECUTE FUNCTION public.db_forecast_payload_integrity();
CREATE TRIGGER section_editable BEFORE INSERT OR UPDATE OR DELETE ON public.proposed_class_section FOR EACH ROW EXECUTE FUNCTION public.db_forecast_payload_integrity();
CREATE TRIGGER decision_editable BEFORE INSERT ON public.forecast_decision_audit_log FOR EACH ROW EXECUTE FUNCTION public.db_forecast_payload_integrity();

-- Global role-change serialization prevents two concurrent last-admin removals.
-- Actual actor authentication and audit insertion remain the trusted Worker/service boundary.
CREATE FUNCTION public.db_preserve_last_admin() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  PERFORM pg_advisory_xact_lock(260002,1);
  IF TG_OP<>'INSERT' AND OLD.app_role='SYSTEM_ADMIN' AND OLD.access_status='ACTIVE' THEN
    IF TG_OP='DELETE' OR NEW.app_role<>'SYSTEM_ADMIN' OR NEW.access_status<>'ACTIVE' THEN
      IF NOT EXISTS(SELECT 1 FROM public.user_access_assignment WHERE clerk_user_id<>OLD.clerk_user_id AND app_role='SYSTEM_ADMIN' AND access_status='ACTIVE') THEN
        RAISE EXCEPTION 'Cannot remove the last active System Administrator' USING ERRCODE='23514';
      END IF;
    END IF;
  END IF;
  IF TG_OP='DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $fn$;
CREATE TRIGGER preserve_last_admin BEFORE INSERT OR UPDATE OR DELETE ON public.user_access_assignment FOR EACH ROW EXECUTE FUNCTION public.db_preserve_last_admin();
