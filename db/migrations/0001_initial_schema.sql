CREATE FUNCTION public.db_student_membership() RETURNS trigger LANGUAGE plpgsql AS $fn$
DECLARE owner_id integer; owner_curriculum integer; mapped_curriculum integer; credits integer;
BEGIN
  IF TG_TABLE_NAME='academic_record' THEN
    owner_id := NEW.student_id;
    SELECT curriculum_id INTO owner_curriculum FROM public.student_profile WHERE student_id=owner_id FOR SHARE;
    IF NOT EXISTS (SELECT 1 FROM public.curriculum_subject WHERE curriculum_id=owner_curriculum AND subject_id=NEW.subject_id) THEN
      RAISE EXCEPTION 'Academic record curriculum mismatch' USING ERRCODE='23514';
    END IF;
    SELECT credit_hours INTO credits FROM public.subject WHERE subject_id=NEW.subject_id FOR SHARE;
    IF NEW.recognized_credits > credits THEN
      RAISE EXCEPTION 'Recognized credits exceed configured subject credits' USING ERRCODE='23514';
    END IF;
  ELSE
    IF TG_TABLE_NAME='semester_offering' THEN owner_id := NEW.student_id;
    ELSIF TG_TABLE_NAME='plan_subject' THEN
      SELECT student_id INTO owner_id FROM public.academic_plan WHERE plan_id=NEW.plan_id FOR SHARE;
    ELSE
      SELECT student_id INTO owner_id FROM public.simulation_scenario WHERE scenario_id=NEW.scenario_id FOR SHARE;
    END IF;
    SELECT curriculum_id INTO owner_curriculum FROM public.student_profile WHERE student_id=owner_id FOR SHARE;
    SELECT curriculum_id INTO mapped_curriculum FROM public.curriculum_subject WHERE curriculum_subject_id=NEW.curriculum_subject_id FOR SHARE;
    IF owner_curriculum IS DISTINCT FROM mapped_curriculum OR owner_curriculum IS NULL THEN
      RAISE EXCEPTION 'Student subject curriculum mismatch' USING ERRCODE='23514';
    END IF;
  END IF;
  RETURN NEW;
END $fn$;
